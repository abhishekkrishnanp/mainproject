from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, DateTime, Float, ForeignKey, JSON
from sqlalchemy.orm import relationship
from app.database import Base


class Assessment(Base):
    """Deep conversational assessment session."""
    __tablename__ = "assessments"

    id = Column(Integer, primary_key=True, index=True)
    student_id = Column(String(50), index=True, nullable=False) # e.g. ACGS-STU-000123 or user id
    status = Column(String(50), default="in_progress") # in_progress, completed
    current_question = Column(Integer, default=0)
    total_questions = Column(Integer, default=25)
    started_at = Column(DateTime, default=datetime.utcnow)
    completed_at = Column(DateTime, nullable=True)
    
    # Store complete dynamic conversation memory state
    assessment_state = Column(JSON, nullable=True)

    # Relationships
    responses = relationship("AssessmentResponse", back_populates="assessment", cascade="all, delete-orphan")


class AssessmentResponse(Base):
    """Every response recorded in the deep self-assessment conversation."""
    __tablename__ = "assessment_responses"

    id = Column(Integer, primary_key=True, index=True)
    assessment_id = Column(Integer, ForeignKey("assessments.id"), nullable=False)
    question_id = Column(String(100), nullable=False)
    question_text = Column(Text, nullable=False)
    answer = Column(Text, nullable=False)
    answer_type = Column(String(50), default="option") # option, text
    phase = Column(String(50), nullable=False) # education, academic, interests, skills, personality, values, goals, work_pref
    created_at = Column(DateTime, default=datetime.utcnow)

    assessment = relationship("Assessment", back_populates="responses")


class CareerProfile(Base):
    """Derived multi-dimensional profile generated by SelfAssessmentAgent."""
    __tablename__ = "career_profiles"

    id = Column(Integer, primary_key=True, index=True)
    student_id = Column(String(50), unique=True, index=True, nullable=False)
    personality_profile = Column(JSON, nullable=True)  # 10 dimensions (Analytical, Creative, Social, Leadership, etc.)
    skills_profile = Column(JSON, nullable=True)
    interest_profile = Column(JSON, nullable=True)
    values_profile = Column(JSON, nullable=True)
    confidence_profile = Column(JSON, nullable=True)
    career_preferences = Column(JSON, nullable=True)
    summary_text = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)


class CareerRecommendationRecord(Base):
    """Initial top career recommendations generated at the end of assessment."""
    __tablename__ = "career_recommendations_records"

    id = Column(Integer, primary_key=True, index=True)
    student_id = Column(String(50), index=True, nullable=False)
    career_name = Column(String(255), nullable=False)
    match_score = Column(Float, nullable=False) # percentage 0-100
    reason = Column(Text, nullable=False)
    supporting_evidence = Column(JSON, nullable=True) # list of points from interview
    concerns = Column(JSON, nullable=True) # list of potential concerns
    skills_needed = Column(JSON, nullable=True) # list of skills to develop
    created_at = Column(DateTime, default=datetime.utcnow)
